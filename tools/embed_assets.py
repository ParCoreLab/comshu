#!/usr/bin/env python3
"""Embed a built static site into a C++ header, byte for byte.

    tools/embed_assets.py <asset-dir> <out-header>

Why the binary is self-contained: pcomm is copied to a login node and run
there behind an SSH port-forward. A server that needs a sibling `dist/`
directory is one that serves a blank page the first time anybody does that, and
the failure looks like a broken UI rather than a missing file.

Why bytes and not a raw string literal. The predecessor embedded one hand-written
HTML file as `R"pcommhtml(...)pcommhtml"`, which is fine for a page you wrote and
a trap for a bundler's output: the delimiter has to be a sequence the content
cannot contain, and minified JS contains arbitrary byte sequences by definition.
It also could not carry a font or an image at all. A byte array has no escape
sequence to collide with, so this stays correct for whatever the bundle grows
into.

The generated header is build-tree only — never committed, because a committed
copy of a build artefact is a copy that goes stale silently.
"""
import sys
import os

# Only what a Vite bundle actually emits, plus the fonts/images one will grow.
# Unknown extensions are served as octet-stream rather than guessed: a wrong
# Content-Type makes a browser silently refuse a module script, which presents
# as a blank page with nothing in the server log.
MIME = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".mjs": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".webp": "image/webp",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".ttf": "font/ttf",
    ".map": "application/json; charset=utf-8",
    ".txt": "text/plain; charset=utf-8",
    ".wasm": "application/wasm",
}


def c_bytes(data: bytes) -> str:
    """One line per 24 bytes: readable in a diff, and short enough that a
    compiler error inside the array names a line a human can find."""
    out = []
    for i in range(0, len(data), 24):
        out.append("    " + "".join(f"0x{b:02x}," for b in data[i : i + 24]))
    return "\n".join(out)


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: embed_assets.py <asset-dir> <out-header>\n")
        return 2
    root, out_path = sys.argv[1], sys.argv[2]

    files = []
    for dirpath, _dirs, names in os.walk(root):
        for n in sorted(names):
            full = os.path.join(dirpath, n)
            # Served path, always '/'-separated and rooted, whatever the host.
            rel = "/" + os.path.relpath(full, root).replace(os.sep, "/")
            files.append((rel, full))
    files.sort()

    if not files:
        sys.stderr.write(f"embed_assets.py: no files under {root}\n")
        return 1

    parts = [
        "// GENERATED by tools/embed_assets.py — do not edit, do not commit.\n",
        f"// Source: {os.path.relpath(root)}\n",
        "#pragma once\n",
        "#include <cstddef>\n\n",
        "namespace pcomm::ui {\n\n",
        "struct Asset {\n",
        "    const char*          path;  // served path, e.g. \"/assets/index.js\"\n",
        "    const char*          mime;\n",
        "    const unsigned char* data;\n",
        "    std::size_t          size;\n",
        "};\n\n",
    ]

    for i, (rel, full) in enumerate(files):
        with open(full, "rb") as f:
            data = f.read()
        parts.append(f"// {rel} ({len(data)} bytes)\n")
        parts.append(f"inline constexpr unsigned char kAssetData{i}[] = {{\n")
        parts.append(c_bytes(data) + "\n};\n\n")

    parts.append("inline constexpr Asset kAssets[] = {\n")
    for i, (rel, full) in enumerate(files):
        mime = MIME.get(os.path.splitext(rel)[1].lower(), "application/octet-stream")
        size = os.path.getsize(full)
        parts.append(f'    {{"{rel}", "{mime}", kAssetData{i}, {size}}},\n')
    parts.append("};\n\n")
    parts.append("inline constexpr std::size_t kAssetCount = "
                 f"{len(files)};\n\n")
    parts.append("}  // namespace pcomm::ui\n")

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w") as f:
        f.write("".join(parts))
    total = sum(os.path.getsize(p) for _r, p in files)
    sys.stderr.write(f"embed_assets.py: {len(files)} file(s), {total} bytes -> {out_path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
