// NCCL's commHash, pinned against vectors produced by NCCL's own source.
//
// WHY A GOLDEN AND NOT A PROPERTY TEST. This function has exactly one job: to
// produce the same number NCCL produces, so that a profiler-plugin row and a
// host-API row for the same communicator join. Every internal property you could
// assert about it — avalanche, determinism, distribution — would still hold if a
// constant were mistyped, and the join would be silently empty. The only thing
// worth testing is agreement with NCCL, so the only test is agreement with NCCL.
//
// WHERE THE NUMBERS CAME FROM. Generated by compiling
// reference/nccl-git/src/include/bitops.h lines 500-548 VERBATIM (eatHash,
// digestHash, getHash) into a throwaway program and printing getHash() for each
// input below. They are NCCL's output, not a second copy of our arithmetic.
//
// If NCCL ever changes getHash, this test keeps passing and the join breaks —
// which is why the real end-to-end check is on hardware: NCCL prints its own
// value as `commId 0x%llx` in the "Init START" line at NCCL_DEBUG=INFO
// (reference/nccl-git/src/init.cc:1912), and the suite compares that string to
// the recorded nccl_comm_hash. This test is the fast local guard; that run is
// the proof.
//
// ENDIANNESS. The vectors are little-endian, as is every host we build for.

#include <cassert>
#include <cstdint>
#include <cstdio>
#include <cstring>

#include "nccl_comm_hash.hpp"

using comshu::providers::nccl::nccl_comm_hash;

namespace {

int g_fail = 0;

void expect_hash(const void* bytes, std::size_t len, std::uint64_t want, const char* what) {
    const std::uint64_t got = nccl_comm_hash(bytes, len);
    const bool          ok = got == want;
    std::printf("  [%s] %-22s got 0x%016llx want 0x%016llx\n", ok ? "ok " : "XX ", what,
                static_cast<unsigned long long>(got), static_cast<unsigned long long>(want));
    if (!ok)
        g_fail = 1;
}

}  // namespace

int main() {
    std::printf("nccl comm hash: the number NCCL hands the profiler plugin\n");

    // NCCL_UNIQUE_ID_BYTES is 128, and that is the length the init path hashes.
    unsigned char id[128];

    std::memset(id, 0, sizeof id);
    expect_hash(id, sizeof id, 0xcc976ec6c24bb53cull, "128 zero bytes");

    for (int i = 0; i < 128; ++i)
        id[i] = static_cast<unsigned char>(i);
    expect_hash(id, sizeof id, 0x6afe1cc17717e1f4ull, "0..127 ramp");

    std::memset(id, 0xff, sizeof id);
    expect_hash(id, sizeof id, 0xb291227e082bb663ull, "128 x 0xff");

    // The shape of a real ncclUniqueId: a small header, then mostly zero. Worth
    // having on its own because it is the case where a bug in the tail-chunk
    // loop would be masked by the leading bytes agreeing.
    std::memset(id, 0, sizeof id);
    // The bytes are the known answer's input and must not change with the
    // project's name: 0x3b9c0d977c7bca36 was computed from exactly these 14.
    std::memcpy(id, "\x02\x00\x00\x00pcomm-test", 14);
    expect_hash(id, sizeof id, 0x3b9c0d977c7bca36ull, "header + zero fill");

    // Lengths that are not a multiple of 8 exercise the partial final chunk,
    // where a memcpy of the wrong size reads adjacent stack and still returns a
    // plausible-looking number.
    expect_hash("abc", 3, 0x751c1b124ef01f18ull, "3 bytes");
    expect_hash("0123456789abcde", 15, 0x5380718f62a8569full, "15 bytes");

    // Zero length still seeds the accumulator and mixes; it must not be 0.
    expect_hash("", 0, 0x75b6431c590e86a2ull, "0 bytes");

    // Not a golden — a guard against the whole thing being replaced by
    // something that ignores its input.
    unsigned char a[128], b[128];
    std::memset(a, 0, sizeof a);
    std::memset(b, 0, sizeof b);
    b[127] = 1;
    const bool differs = nccl_comm_hash(a, sizeof a) != nccl_comm_hash(b, sizeof b);
    std::printf("  [%s] the last byte of the id changes the hash\n", differs ? "ok " : "XX ");
    if (!differs)
        g_fail = 1;

    std::printf("%s\n", g_fail ? "FAIL" : "PASS — commHash agrees with NCCL");
    return g_fail;
}
